export function normalizeCurrencyCode(code?: string | null): string {
  const clean = (code || '').trim().toUpperCase();
  if (!clean) return 'PKR';
  if (clean === 'RMB') return 'CNY';
  return clean;
}

export function getWorldCurrency(code?: string | null): WorldCurrency {
  const raw = (code || 'PKR').trim().toUpperCase();
  if (raw === 'RMB') {
    return { code: 'CNY', name: 'Chinese Yuan (RMB)', symbol: '¥', country: 'China' };
  }
  const found = WORLD_CURRENCIES.find((c) => c.code === raw);
  if (found) return found;
  return { code: raw || 'PKR', name: raw || 'Unknown Currency', symbol: raw || 'PKR' };
}
